def _remover_imgs_sem_src(html: str) -> str:
  return re.sub(r'<img\b(?![^>]*\bsrc\s*=\s*["\'][^"\']+["\'])[^>]*?/?>', "", html, flags=re.IGNORECASE)


class _FiltroAvisosPisa(logging.Filter):
  _IGNORADOS = ("Ignoring CSS properties xhtml2pdf does not implement",)

  def filter(self, record: logging.LogRecord) -> bool:
    msg = record.getMessage()
    return not any(trecho in msg for trecho in self._IGNORADOS)


def _executar_pisa_sem_aviso_css(html: str, dest: BytesIO):
  loggers = (logging.getLogger("xhtml2pdf.parser"), logging.getLogger("xhtml2pdf.tags"))
  filtro = _FiltroAvisosPisa()
  for lg in loggers:
    lg.addFilter(filtro)
  try:
    return pisa.CreatePDF(html, dest=dest, encoding="utf-8")
  finally:
    for lg in loggers:
      lg.removeFilter(filtro)


def _perguntar_sn(msg: str) -> str:
  resp = ""
  while resp not in ("s", "n"):
    resp = input(msg).strip().lower()
  return resp


def existe_arquivo(arq) -> bool:
  return Path(arq).exists()


def _resolver_destino(alvo: Path) -> Path:
  if not existe_arquivo(alvo):
    return alvo
  if _perguntar_sn(f" O arquivo {alvo.name} já existe no ambiente. Você deseja sobrescrever o arquivo (s/n)? ") == "s":
    return alvo
  n = 1
  while (cand := alvo.with_name(f"{alvo.stem}_v{n}.pdf")).exists():
    n += 1
  return cand


def _confirmar_e_salvar(saida: dict, dados: bytes | None, alvo_sugerido: Path | None, chave_saida: str = "pdf_gerado", confirmar: bool = True) -> dict:
  if dados is None or alvo_sugerido is None or (confirmar and _perguntar_sn(f" Deseja salvar {alvo_sugerido.name}? (s/n) ") == "n"):
    print(" Não houve alterações. Nenhum arquivo foi salvo.")
    return saida
  final = _resolver_destino(alvo_sugerido)
  final.write_bytes(dados)
  print(f" O arquivo {final.name} foi salvo com sucesso.")
  saida[chave_saida] = str(final)
  return saida


def _info_vazia(motivo: str, falhou: bool = False) -> dict:
  return {"tem_texto": False, "chars": 0, "paginas_com_texto": 0, "dados": None, "conteudo_texto": "", "motivo": motivo, "falhou": falhou}


def _rodar_cli_bytes(comandos: list[list[str]], entrada: bytes, validar_png: bool = False, timeout: int = 15) -> bytes | None:
  for cmd in comandos:
    try:
      res = subprocess.run(cmd, input=entrada, capture_output=True, check=False, timeout=timeout)
      if res.returncode == 0 and res.stdout and (not validar_png or res.stdout.startswith(b"\x89PNG")):
        return res.stdout
    except (subprocess.SubprocessError, OSError):
      continue
  return None


def _analisar_pdf(src, min_chars: int = MIN_CHARS, extrair_texto: bool = True) -> tuple[int, list[dict], str]:
  try:
    reader = src if isinstance(src, PdfReader) else PdfReader(src)
    pags, textos = [], []
    for i, page in enumerate(reader.pages, 1):
      txt = (page.extract_text() or "").strip()
      if extrair_texto and txt:
        textos.append(txt)
      n, img = len(txt), len(page.images)
      st = "texto_selecionavel" if n >= min_chars else ("escaneado_ou_imagem" if img else ("vazio_ou_pouco_texto" if n else "em_branco"))
      pags.append({"pagina": i, "chars": n, "imagens": img, "status": st})
    return sum(p["chars"] for p in pags), pags, ("\n\n".join(textos) if extrair_texto else "")
  except (PdfReadError, OSError, ValueError, RuntimeError):
    return 0, [], ""


def extrair_texto_pdf(src) -> str:
  return _analisar_pdf(src, extrair_texto=True)[2]


def _chars_pdf(src, min_chars: int = MIN_CHARS) -> tuple[int, list[dict]]:
  return _analisar_pdf(src, min_chars, extrair_texto=False)[:2]


def _converter_imagem_cli_para_png_memoria(dados_img: bytes, ext: str) -> bytes | None:
  fmt = ext.lstrip(".").lower()
  cmds = ([["magick", f"{fmt}:-", "png:-"], ["convert", f"{fmt}:-", "png:-"]] if fmt else [])
  cmds += [["magick", "-", "png:-"], ["convert", "-", "png:-"], ["ffmpeg", "-v", "error", "-i", "pipe:0", "-f", "image2pipe", "-vcodec", "png", "pipe:1"]]
  return _rodar_cli_bytes(cmds, dados_img, validar_png=True)


def _imagem_para_pdf_bytes(img: Path, dpi: int = 300) -> tuple[bytes | None, str | None]:
  if not existe_arquivo(img):
    return None, f"arquivo_nao_encontrado ({img.resolve()})"
  if img.stat().st_size == 0:
    return None, f"arquivo_vazio ({img.name})"
  try:
    return img2pdf.convert(str(img)), None
  except (OSError, ValueError, RuntimeError, ImageOpenError) as e1:
    try:
      Image.MAX_IMAGE_PIXELS = None
      buf = BytesIO()
      with Image.open(img) as im:
        ImageOps.exif_transpose(im).convert("RGB").save(buf, format="JPEG", quality=95, dpi=(dpi, dpi))
      return img2pdf.convert(buf.getvalue()), None
    except (OSError, ValueError, RuntimeError, ImageOpenError, UnidentifiedImageError) as e2:
      png_bytes = _converter_imagem_cli_para_png_memoria(img.read_bytes(), img.suffix)
      if png_bytes:
        try:
          return img2pdf.convert(png_bytes), None
        except (OSError, ValueError, RuntimeError, ImageOpenError) as e3:
          return None, f"falha_pos_cli ({type(e3).__name__}: {e3})"
      return None, f"{type(e1).__name__}: {e1} | {type(e2).__name__}: {e2}"


def _aplicar_ocr(entrada, idioma: str, min_chars: int, preservar_paginas_com_texto: bool = False) -> dict:
  try:
    saida = BytesIO()
    ocrmypdf.ocr(BytesIO(entrada) if isinstance(entrada, bytes) else str(entrada), saida, language=idioma, output_type="pdf", skip_text=preservar_paginas_com_texto, force_ocr=not preservar_paginas_com_texto, progress_bar=False)
    dados = saida.getvalue()
    chars, pags, texto = _analisar_pdf(BytesIO(dados), min_chars)
    ok = chars >= min_chars
    return {"tem_texto": ok, "chars": chars, "dados": dados, "conteudo_texto": texto, "paginas_com_texto": sum(p["status"] == "texto_selecionavel" for p in pags), "motivo": "texto_detectado_via_ocrmypdf" if ok else "pouco_ou_nenhum_texto_detectado"}
  except ocrmypdf.exceptions.MissingDependencyError as e:
    return _info_vazia(f"dependencia_sistema_ausente ({e})", falhou=True)
  except (OSError, ValueError, RuntimeError, ocrmypdf.exceptions.OcrmypdfError) as e:
    return _info_vazia(f"falha_ou_sem_texto_ocr ({type(e).__name__}: {e})", falhou=True)


def _preparar_imagem_para_pdf(img: Path, destino_com_texto: Path, destino_sem_texto: Path, idioma: str, min_chars: int) -> tuple[dict, bytes | None, Path | None]:
  base, erro = _imagem_para_pdf_bytes(img)
  if base is None:
    return _info_vazia(f"falha_converter_imagem_para_pdf ({erro})", falhou=True), None, None
  info = _aplicar_ocr(base, idioma, min_chars)
  if info.get("falhou"):
    return info, None, None
  info["_dados_sem_texto"], info["_alvo_sem_texto"] = base, destino_sem_texto
  ok = info["tem_texto"]
  return info, (info["dados"] if ok else base), (destino_com_texto if ok else destino_sem_texto)


def _preparar_ocr_em_pdf_existente(pdf: Path, alvo: Path, idioma: str, min_chars: int, paginas_com_texto_antes: int) -> tuple[dict, bytes | None, Path | None]:
  info = _aplicar_ocr(pdf, idioma, min_chars, preservar_paginas_com_texto=paginas_com_texto_antes > 0)
  if info["dados"] and info["paginas_com_texto"] > paginas_com_texto_antes:
    info["tem_texto"] = True
    return info, info["dados"], alvo
  info["tem_texto"] = False
  if info["motivo"] == "texto_detectado_via_ocrmypdf":
    info["motivo"] = "ocr_nao_adicionou_texto"
  return info, None, None


def _pdf_sem_ocr_bytes(pdf: Path) -> bytes:
  writer, buf = PdfWriter(), BytesIO()
  for page in PdfReader(pdf).pages:
    writer.add_page(page)
  writer.write(buf)
  return buf.getvalue()


def _preparar_pdf(pdf: Path, alvo: Path, idioma: str, min_chars: int) -> tuple[dict, bytes | None, Path | None]:
  try:
    reader = PdfReader(pdf)
    _ = len(reader.pages)
  except (PdfReadError, OSError, ValueError, RuntimeError) as e:
    return {"tipo": "pdf_invalido_ou_corrompido", "acao": f"arquivo PDF truncado ou corrompido ({type(e).__name__}); nada salvo", "com_txt": 0, "info_ocr": None, "paginas": [], "conteudo_texto": ""}, None, None

  _, pags, conteudo_texto = _analisar_pdf(reader, min_chars)
  uteis = [p for p in pags if p["status"] != "em_branco"]
  tot, com = len(uteis), sum(p["status"] == "texto_selecionavel" for p in uteis)
  esc = sum(p["status"] == "escaneado_ou_imagem" for p in uteis)
  i, dados, dest = None, None, None
  if tot and com == tot:
    tipo, acao = "texto_selecionavel", "já tem texto selecionável; nada salvo"
  elif tot and (esc == tot or (com and esc)):
    tipo = "escaneado" if esc == tot else "misto"
    i, dados_ocr, _ = _preparar_ocr_em_pdf_existente(pdf, alvo, idioma, min_chars, com)
    if i and i.get("conteudo_texto"):
      conteudo_texto = i["conteudo_texto"]
    if dados_ocr is not None:
      i["_dados_sem_texto"], i["_alvo_sem_texto"] = lambda p=pdf: _pdf_sem_ocr_bytes(p), alvo.with_name(f"{pdf.stem}{SUFIXO_SEM_TEXTO}.pdf")
      dados, dest, acao = dados_ocr, alvo, "texto reconhecido; salvo como PDF com texto selecionável"
    elif i.get("falhou"):
      acao = "falha no OCR; nada salvo (veja detalhe_ocr)"
    else:
      tipo = "escaneado_sem_texto" if tipo == "escaneado" else tipo
      acao = "nenhum texto reconhecido por OCR; nada salvo"
  else:
    tipo, acao = "indefinido_ou_vazio", "inspecionar manualmente ou aplicar OCR/VLM; nada salvo"
  return {"tipo": tipo, "acao": acao, "com_txt": com, "info_ocr": i, "paginas": pags, "conteudo_texto": conteudo_texto}, dados, dest


def _pdf_bytes_para_pdf_imagem_bytes(pdf_bytes: bytes, dpi: int = 150) -> bytes | None:
  try:
    total = len(PdfReader(BytesIO(pdf_bytes)).pages)
    if not total:
      return None
    paginas_jpg = []
    for p in range(1, total + 1):
      jpg = _rodar_cli_bytes([["gs", "-q", "-dSAFER", "-dBATCH", "-dNOPAUSE", "-sDEVICE=jpeg", "-dJPEGQ=92", f"-r{dpi}", f"-dFirstPage={p}", f"-dLastPage={p}", "-sOutputFile=-", "-"]], pdf_bytes)
      if not jpg:
        return None
      paginas_jpg.append(jpg)
    return img2pdf.convert(paginas_jpg)
  except (subprocess.SubprocessError, OSError, ValueError, RuntimeError):
    return None


def _converter_emf_para_png_memoria(dados_emf: bytes) -> bytes | None:
  cmds = [["magick", "emf:-", "png:-"], ["convert", "emf:-", "png:-"], ["gs", "-q", "-dSAFER", "-dBATCH", "-dNOPAUSE", "-sDEVICE=png16m", "-r150", "-sOutputFile=-", "-"]]
  return _rodar_cli_bytes(cmds, dados_emf, validar_png=True)


def _tratar_imagem_word(image):
  with image.open() as stream:
    raw = stream.read()
  content_type = image.content_type
  if content_type in _TIPOS_EMF_WMF:
    png_bytes = _converter_emf_para_png_memoria(raw)
    if not png_bytes:
      return []
    raw, content_type = png_bytes, "image/png"
  return {"src": f"data:{content_type};base64,{base64.b64encode(raw).decode('ascii')}"}


def _preparar_word_para_pdf(doc: Path, alvo: Path, min_chars: int) -> tuple[dict, bytes | None, Path | None]:
  if doc.suffix.lower() == ".doc":
    return _info_vazia("formato_doc_nao_suportado"), None, None
  try:
    with open(doc, "rb") as f:
      corpo = _remover_imgs_sem_src(mammoth.convert_to_html(f, convert_image=mammoth.images.img_element(_tratar_imagem_word)).value)
    buf = BytesIO()
    if _executar_pisa_sem_aviso_css(f'<html><head><meta charset="utf-8"><style>{_CSS_WORD}</style></head><body>{corpo}</body></html>', buf).err:
      return _info_vazia("falha_xhtml2pdf"), None, None
    dados = buf.getvalue()
    chars, _, texto = _analisar_pdf(BytesIO(dados), min_chars)
  except (OSError, ValueError, RuntimeError) as e:
    return _info_vazia(f"falha_conversao_word ({type(e).__name__})"), None, None
  ok = chars >= min_chars
  info = _info_vazia("convertido_via_mammoth_xhtml2pdf" if ok else "convertido_mas_sem_texto_selecionavel")
  info.update({"tem_texto": ok, "chars": chars, "conteudo_texto": texto, "_dados_sem_texto": lambda b=dados: _pdf_bytes_para_pdf_imagem_bytes(b), "_alvo_sem_texto": doc.with_name(f"{doc.stem}{SUFIXO_SEM_TEXTO}.pdf")})
  return info, dados, alvo


def _classificar_arquivo(caminho, idioma_ocr="por", min_chars=MIN_CHARS) -> tuple[dict, bytes | None, Path | None]:
  arq, ext = Path(caminho), Path(caminho).suffix.lower()
  if ext in EXT_IMAGENS:
    i, dados, alvo = _preparar_imagem_para_pdf(arq, arq.with_name(f"{arq.stem}{SUFIXO_COM_TEXTO}.pdf"), arq.with_name(f"{arq.stem}{SUFIXO_SEM_TEXTO}.pdf"), idioma_ocr, min_chars)
    tipo, acao = ("imagem_falha_conversao", "falha na conversão ou no OCR; nada salvo (veja detalhe_ocr)") if i.get("falhou") else (
        ("imagem_com_texto", "salvo como PDF com texto selecionável") if i["tem_texto"] else ("imagem_sem_texto", "salvo como PDF escaneado sem texto selecionável"))
    return {"arquivo": arq.name, "tipo": tipo, "selecionavel": False, "texto_convertivel": i["tem_texto"], "chars_ocr": i["chars"], "pdf_gerado": str(alvo) if alvo else None, "detalhe_ocr": i["motivo"], "acao_sugerida": acao, "conteudo_texto": i.get("conteudo_texto", ""), "_info": i}, dados, alvo
  if ext in EXT_WORD:
    i, dados, alvo = _preparar_word_para_pdf(arq, arq.with_name(f"{arq.stem}{SUFIXO_WORD}.pdf"), min_chars)
    acao = ("convertido e salvo como PDF com texto selecionável" if dados and i["tem_texto"] else (
        "PDF salvo, mas sem texto selecionável (documento só com imagens?)" if dados else (
            "formato .doc não suportado; salve como .docx no Word e tente de novo; nada salvo" if i["motivo"] == "formato_doc_nao_suportado" else f"nada salvo ({i['motivo']})")))
    return {"arquivo": arq.name, "tipo": "word_docx" if ext == ".docx" else "word_doc", "selecionavel": i["tem_texto"], "texto_convertivel": i["tem_texto"], "chars_ocr": 0, "chars_texto": i["chars"], "pdf_gerado": str(alvo) if alvo else None, "detalhe_ocr": None, "detalhe_conversao": i["motivo"], "acao_sugerida": acao, "conteudo_texto": i.get("conteudo_texto", ""), "_info": i}, dados, alvo
  if ext != ".pdf":
    return {"arquivo": arq.name, "tipo": "outro", "selecionavel": False, "texto_convertivel": False, "acao_sugerida": "verificar formato", "conteudo_texto": ""}, None, None
  r, dados, alvo = _preparar_pdf(arq, arq.with_name(f"{arq.stem}{SUFIXO_COM_TEXTO}.pdf"), idioma_ocr, min_chars)
  i, com = r["info_ocr"], r["com_txt"]
  return {"arquivo": arq.name, "tipo": r["tipo"], "selecionavel": com > 0, "texto_convertivel": com > 0 or bool(i and i["tem_texto"]), "chars_ocr": i["chars"] if i else 0, "pdf_gerado": str(alvo) if alvo else None, "detalhe_ocr": i["motivo"] if i else None, "acao_sugerida": r["acao"], "paginas": r["paginas"], "conteudo_texto": r.get("conteudo_texto", ""), "_info": i}, dados, alvo


def converter_pdf_escaneado_para_pdf(caminho_pdf, caminho_pdf_saida=None, idioma_ocr="por", min_chars=MIN_CHARS) -> dict:
  pdf = Path(caminho_pdf)
  r, dados, alvo = _preparar_pdf(pdf, Path(caminho_pdf_saida) if caminho_pdf_saida else pdf.with_name(f"{pdf.stem}{SUFIXO_COM_TEXTO}.pdf"), idioma_ocr, min_chars)
  i = r["info_ocr"]
  ok = r["tipo"] == "texto_selecionavel" or bool(i and i["tem_texto"])
  return _confirmar_e_salvar({"arquivo_origem": pdf.name, "arquivo_saida": str(alvo) if alvo else None, "modo": "pdf_texto_selecionavel" if ok else "pdf_sem_texto_ocr", "tipo": r["tipo"], "biblioteca": "ocrmypdf", "chars_ocr": i["chars"] if i else 0, "detalhe_ocr": i["motivo"] if i else None, "acao_sugerida": r["acao"]}, dados, alvo, "arquivo_saida")


def converter_word_para_pdf(caminho_word, caminho_pdf_saida=None, min_chars=MIN_CHARS) -> dict:
  doc = Path(caminho_word)
  i, dados, alvo = _preparar_word_para_pdf(doc, Path(caminho_pdf_saida) if caminho_pdf_saida else doc.with_name(f"{doc.stem}{SUFIXO_WORD}.pdf"), min_chars)
  return _confirmar_e_salvar({"arquivo_origem": doc.name, "arquivo_saida": str(alvo) if alvo else None, "modo": "pdf_texto_selecionavel" if i["tem_texto"] else "pdf_sem_texto", "biblioteca": "mammoth+xhtml2pdf", "chars_texto": i["chars"], "detalhe_conversao": i["motivo"]}, dados, alvo, "arquivo_saida")


def converter_imagem_para_pdf(caminho_imagem, caminho_pdf_saida, idioma_ocr="por", min_chars=MIN_CHARS) -> dict:
  img, out = Path(caminho_imagem), Path(caminho_pdf_saida)
  i, dados, alvo = _preparar_imagem_para_pdf(img, out, out, idioma_ocr, min_chars)
  modo, bib = ("nada_salvo", None) if i.get("falhou") else (("pdf_texto_selecionavel", "ocrmypdf") if i["tem_texto"] else ("pdf_escaneado_sem_texto", "img2pdf"))
  return _confirmar_e_salvar({"arquivo_origem": img.name, "arquivo_saida": str(alvo) if alvo else None, "modo": modo, "biblioteca": bib, "chars_ocr": i["chars"], "detalhe_ocr": i["motivo"]}, dados, alvo, "arquivo_saida")


def processar_arquivo(caminho, idioma_ocr=IDIOMA_OCR, min_chars=MIN_CHARS) -> dict:
  arq = Path(caminho)
  if not existe_arquivo(arq):
    print(f"O {arq.name} não existe. Verifique o nome do arquivo.")
    return {"arquivo": arq.name, "tipo": "inexistente", "selecionavel": False, "texto_convertivel": False, "acao_sugerida": "verificar nome do arquivo"}

  classificacao, dados, alvo = _classificar_arquivo(caminho, idioma_ocr, min_chars)
  conteudo_texto = classificacao.pop("conteudo_texto", "")
  info_aux = classificacao.pop("_info", None) or {}
  print(f" Arquivo: {caminho} \n Detecção: {classificacao}")
  if conteudo_texto and (primeiro_paragrafo := next((limpo for p in conteudo_texto.split("\n\n") if (limpo := " ".join(p.split()))), "")):
    print(f' Trecho: "{primeiro_paragrafo}"')

  if dados is None or alvo is None:
    return _confirmar_e_salvar(classificacao, None, None, confirmar=False)

  if classificacao.get("tipo") in ("imagem_com_texto", "escaneado", "misto") or classificacao.get("texto_convertivel"):
    if _perguntar_sn(f" Há texto no conteúdo do arquivo {arq.name}. Você deseja converter o arquivo para PDF com texto selecionável? (s/n) ") == "s":
      if arq.suffix.lower() in EXT_WORD and alvo is not None:
        alvo = alvo.with_name(f"{arq.stem}{SUFIXO_WORD}.pdf")
      classificacao["acao_sugerida"] = "texto reconhecido; salvo como PDF com texto selecionável"
    elif "_dados_sem_texto" in info_aux:
      alt = info_aux["_dados_sem_texto"]
      dados, alvo = alt() if callable(alt) else alt, info_aux["_alvo_sem_texto"]
      classificacao["texto_convertivel"] = False
      classificacao["acao_sugerida"] = "salvo como PDF escaneado sem texto selecionável"
      if arq.suffix.lower() in EXT_IMAGENS:
        classificacao["tipo"] = "imagem_sem_texto"

  if _perguntar_sn(f" Deseja salvar {alvo.name}? (s/n) ") == "n":
    return _confirmar_e_salvar(classificacao, None, None, confirmar=False)

  return _confirmar_e_salvar(classificacao, dados, alvo, confirmar=False)

